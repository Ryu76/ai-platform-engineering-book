"""Deterministic, offline-safe building blocks for a bounded multi-agent review workflow."""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Protocol


class WorkflowConfigurationError(ValueError):
    """Raised when a workflow boundary is configured with an unsafe value."""


class AgentProtocolError(RuntimeError):
    """Raised when a mock agent cannot satisfy its deterministic script."""


class ReviewDecision(StrEnum):
    """The only decisions a reviewer may return for a draft."""

    APPROVE = "approve"
    REVISE = "revise"


class HumanApproval(StrEnum):
    """Explicit human decision required before QA may run."""

    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"


class WorkflowStatus(StrEnum):
    """Terminal or safely-paused workflow states."""

    AWAITING_HUMAN_APPROVAL = "awaiting_human_approval"
    COMPLETED = "completed"
    HUMAN_REJECTED = "human_rejected"
    REVIEW_LIMIT_REACHED = "review_limit_reached"


@dataclass(frozen=True)
class AgentContext:
    """The minimal, immutable context supplied to one role invocation."""

    task: str
    iteration: int
    messages: tuple[AgentMessage, ...]


@dataclass(frozen=True)
class AgentMessage:
    """An auditable message generated by one named role."""

    role: str
    content: str
    iteration: int


@dataclass(frozen=True)
class AgentResponse:
    """A deterministic role response and an optional review decision."""

    content: str
    review: ReviewDecision | None = None


class Agent(Protocol):
    """A role boundary that can be replaced without changing the orchestrator."""

    def act(self, context: AgentContext) -> AgentResponse:
        """Return one response for the supplied, immutable workflow context."""


class DeterministicMockAgent:
    """Offline mock agent that consumes a fixed response script in call order.

    It has no network client, tool executor, environment lookup, or fallback response.
    Exhausting the script fails closed, making unintended extra iterations visible in tests.
    """

    def __init__(self, *, role: str, responses: tuple[AgentResponse, ...]) -> None:
        if not role.strip():
            raise WorkflowConfigurationError("role must not be empty")
        if not responses:
            raise WorkflowConfigurationError("responses must not be empty")
        self.role = role
        self._responses = responses
        self.calls: list[AgentContext] = []

    def act(self, context: AgentContext) -> AgentResponse:
        """Record the local call and return its preconfigured response."""
        response_index = len(self.calls)
        if response_index >= len(self._responses):
            raise AgentProtocolError(
                f"{self.role} mock has no response for call {response_index + 1}"
            )
        self.calls.append(context)
        return self._responses[response_index]


@dataclass(frozen=True)
class WorkflowResult:
    """The complete audit trail and terminal status of a single task."""

    status: WorkflowStatus
    messages: tuple[AgentMessage, ...]
    review_cycles: int


class BoundedReviewWorkflow:
    """Coordinate five roles with finite review cycles and a human QA gate."""

    def __init__(
        self,
        *,
        planner: Agent,
        researcher: Agent,
        developer: Agent,
        reviewer: Agent,
        qa: Agent,
        max_review_cycles: int = 2,
    ) -> None:
        if isinstance(max_review_cycles, bool) or not isinstance(max_review_cycles, int):
            raise WorkflowConfigurationError("max_review_cycles must be a positive integer")
        if max_review_cycles < 1:
            raise WorkflowConfigurationError("max_review_cycles must be a positive integer")
        self._planner = planner
        self._researcher = researcher
        self._developer = developer
        self._reviewer = reviewer
        self._qa = qa
        self._max_review_cycles = max_review_cycles

    def run(
        self, *, task: str, human_approval: HumanApproval = HumanApproval.PENDING
    ) -> WorkflowResult:
        """Run a finite offline workflow; QA occurs only after explicit approval.

        A rejected request fails closed before any agent is called. A pending request stops
        after reviewer approval and preserves the messages needed by a human approver.
        """
        if not isinstance(task, str) or not task.strip():
            raise WorkflowConfigurationError("task must be a non-empty string")
        if not isinstance(human_approval, HumanApproval):
            raise WorkflowConfigurationError("human_approval must be a HumanApproval value")
        if human_approval is HumanApproval.REJECTED:
            return WorkflowResult(WorkflowStatus.HUMAN_REJECTED, (), 0)

        messages: list[AgentMessage] = []
        self._append(messages, "planner", self._planner, task, 0)
        self._append(messages, "researcher", self._researcher, task, 0)

        for cycle in range(1, self._max_review_cycles + 1):
            self._append(messages, "developer", self._developer, task, cycle)
            reviewer_response = self._call(self._reviewer, task, cycle, messages)
            self._validate_response(reviewer_response)
            messages.append(AgentMessage("reviewer", reviewer_response.content, cycle))

            if reviewer_response.review is ReviewDecision.REVISE:
                continue
            if reviewer_response.review is not ReviewDecision.APPROVE:
                raise AgentProtocolError(
                    "reviewer response must include an explicit review decision"
                )
            if human_approval is HumanApproval.PENDING:
                return WorkflowResult(
                    WorkflowStatus.AWAITING_HUMAN_APPROVAL, tuple(messages), cycle
                )

            self._append(messages, "qa", self._qa, task, cycle)
            return WorkflowResult(WorkflowStatus.COMPLETED, tuple(messages), cycle)

        return WorkflowResult(
            WorkflowStatus.REVIEW_LIMIT_REACHED, tuple(messages), self._max_review_cycles
        )

    @staticmethod
    def _call(
        agent: Agent, task: str, iteration: int, messages: list[AgentMessage]
    ) -> AgentResponse:
        return agent.act(AgentContext(task=task, iteration=iteration, messages=tuple(messages)))

    def _append(
        self, messages: list[AgentMessage], role: str, agent: Agent, task: str, iteration: int
    ) -> None:
        response = self._call(agent, task, iteration, messages)
        self._validate_response(response)
        messages.append(AgentMessage(role, response.content, iteration))

    @staticmethod
    def _validate_response(response: object) -> None:
        """Reject malformed local agent output before it reaches another role."""
        if not isinstance(response, AgentResponse):
            raise AgentProtocolError("agent response must be an AgentResponse")
        if not isinstance(response.content, str) or not response.content.strip():
            raise AgentProtocolError("agent response content must be a non-empty string")
