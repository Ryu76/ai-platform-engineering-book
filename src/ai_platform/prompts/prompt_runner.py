"""Versioned Prompt assets and recorded-output comparisons that never call an LLM."""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Literal

from ai_platform.prompts.prompt_templates import (
    PromptConfigurationError,
    PromptSections,
    _require_text,
)
from ai_platform.prompts.structured_output import (
    StructuredOutputError,
    validate_classification_json,
)


class PromptVersionError(PromptConfigurationError):
    """A versioned Prompt or its recorded comparison data violates its contract."""


Category = Literal["billing", "technical", "unknown"]
_VERSION_PATTERN = re.compile(r"v[1-9][0-9]*\Z")


@dataclass(frozen=True, slots=True)
class VersionedPrompt:
    """A reviewable Prompt template with an immutable, human-readable version ID.

    Rendering only produces a string. It deliberately does not select a model, read an
    API key, make a network request, or imply that a recorded answer was generated by
    this process.
    """

    version: str
    change_summary: str
    sections: PromptSections

    def __post_init__(self) -> None:
        """Reject ambiguous version metadata before it becomes a comparison artifact."""
        version = _require_text("version", self.version)
        if not _VERSION_PATTERN.fullmatch(version):
            raise PromptVersionError("version must use the form v1, v2, and so on")
        _require_text("change_summary", self.change_summary)
        if not isinstance(self.sections, PromptSections):
            raise PromptVersionError("sections must be a PromptSections instance")

    def render(self, user_input: str) -> str:
        """Place owned version metadata before the template and untrusted input."""
        return (
            f"[PROMPT VERSION]\n{self.version.strip()}\n\n"
            f"[CHANGE SUMMARY]\n{self.change_summary.strip()}\n\n"
            f"{self.sections.render(user_input)}"
        )


@dataclass(frozen=True, slots=True)
class PromptComparisonCase:
    """One reviewed input and its expected support category for offline comparison."""

    case_id: str
    user_input: str
    expected_category: Category

    def __post_init__(self) -> None:
        """Ensure a case can be identified and evaluated without an external service."""
        _require_text("case_id", self.case_id)
        _require_text("user_input", self.user_input)
        if self.expected_category not in {"billing", "technical", "unknown"}:
            raise PromptVersionError("expected_category must be billing, technical, or unknown")


@dataclass(frozen=True, slots=True)
class RecordedClassification:
    """A manually recorded candidate response; it is input to evaluation, not model output."""

    case_id: str
    raw_response: str

    def __post_init__(self) -> None:
        """Require an explicit case mapping and non-empty recorded response."""
        _require_text("case_id", self.case_id)
        _require_text("raw_response", self.raw_response)


@dataclass(frozen=True, slots=True)
class PromptCaseComparison:
    """The validation and category-match result for one version/case pair."""

    case_id: str
    schema_valid: bool
    category_matches: bool
    error_message: str | None = None


@dataclass(frozen=True, slots=True)
class PromptVersionComparison:
    """Aggregated, reproducible evidence for one Prompt version."""

    version: str
    cases: tuple[PromptCaseComparison, ...]

    @property
    def total_cases(self) -> int:
        """Return the number of reviewed cases."""
        return len(self.cases)

    @property
    def schema_valid_count(self) -> int:
        """Return how many recorded responses meet the JSON schema."""
        return sum(case.schema_valid for case in self.cases)

    @property
    def category_match_count(self) -> int:
        """Return how many responses are valid and have the expected category."""
        return sum(case.category_matches for case in self.cases)

    @property
    def schema_valid_rate(self) -> float:
        """Return the schema-validation rate, or 0.0 for an empty comparison."""
        return self.schema_valid_count / self.total_cases if self.cases else 0.0

    @property
    def category_accuracy(self) -> float:
        """Return the expected-category match rate, or 0.0 for an empty comparison."""
        return self.category_match_count / self.total_cases if self.cases else 0.0


def compare_recorded_classifications(
    prompt: VersionedPrompt,
    cases: tuple[PromptComparisonCase, ...],
    recorded_outputs: tuple[RecordedClassification, ...],
) -> PromptVersionComparison:
    """Compare fixed candidate JSON against reviewed cases without calling a model.

    Every case must have exactly one response, and unknown or duplicate identifiers fail
    closed. Invalid JSON is recorded as a failed schema/category result so a reviewer can
    compare candidates rather than silently repairing a response.
    """
    if not isinstance(prompt, VersionedPrompt):
        raise PromptVersionError("prompt must be a VersionedPrompt instance")
    _validate_case_set(cases, recorded_outputs)
    outputs_by_case = {output.case_id.strip(): output for output in recorded_outputs}
    comparisons: list[PromptCaseComparison] = []
    for case in cases:
        case_id = case.case_id.strip()
        try:
            classification = validate_classification_json(outputs_by_case[case_id].raw_response)
        except StructuredOutputError:
            comparisons.append(
                PromptCaseComparison(
                    case_id=case_id,
                    schema_valid=False,
                    category_matches=False,
                    error_message="response does not match the SupportClassification JSON schema",
                )
            )
            continue
        comparisons.append(
            PromptCaseComparison(
                case_id=case_id,
                schema_valid=True,
                category_matches=classification.category == case.expected_category,
            )
        )
    return PromptVersionComparison(prompt.version.strip(), tuple(comparisons))


def _validate_case_set(
    cases: tuple[PromptComparisonCase, ...],
    recorded_outputs: tuple[RecordedClassification, ...],
) -> None:
    """Require non-empty, typed, one-to-one comparison inputs before scoring them."""
    if not isinstance(cases, tuple) or not cases or not all(
        isinstance(case, PromptComparisonCase) for case in cases
    ):
        raise PromptVersionError("cases must be a non-empty tuple of PromptComparisonCase values")
    if not isinstance(recorded_outputs, tuple) or not all(
        isinstance(output, RecordedClassification) for output in recorded_outputs
    ):
        raise PromptVersionError(
            "recorded_outputs must be a tuple of RecordedClassification values"
        )
    case_ids = tuple(case.case_id.strip() for case in cases)
    output_ids = tuple(output.case_id.strip() for output in recorded_outputs)
    if len(set(case_ids)) != len(case_ids):
        raise PromptVersionError("cases must not contain duplicate case_id values")
    if len(set(output_ids)) != len(output_ids):
        raise PromptVersionError("recorded_outputs must not contain duplicate case_id values")
    if set(case_ids) != set(output_ids):
        raise PromptVersionError(
            "recorded_outputs must contain exactly one response for every case"
        )
